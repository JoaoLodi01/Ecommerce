   IF ((NEW.CFOP = '5933') AND (NEW.CSOSN IS NULL)) THEN
      IF (COALESCE(NEW.VALORALIQUOTAISSQN, 0) > 0) THEN
         SET NEW.VALORBCISSQN = NEW.VALORLIQUIDO;
         SET NEW.VALORISSQN = (NEW.VALORBCISSQN * COALESCE(NEW.VALORALIQUOTAISSQN, 0)) / 100;
      END IF;
   END IF;
   
   IF (EXCLUIBCPISCOFINS <> '1') THEN
      SET NEW.VALORBCPIS = NEW.VALORLIQUIDO;
      SET NEW.VALORPIS = (NEW.VALORBCPIS * COALESCE(NEW.PERCPIS, 0)) / 100;
