            SET NEW.VALORBCICMS = NEW.VALORLIQUIDO * (1 - (NEW.PERCREDUCAOBC / 100));
         ELSE
            SET NEW.VALORBCICMS = NEW.VALORLIQUIDO;
         END IF;
         SET NEW.VALORICMS = (NEW.VALORBCICMS * COALESCE(NEW.PERCICMS, 0)) / 100;
      END IF;
