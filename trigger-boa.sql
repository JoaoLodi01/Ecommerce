BEGIN
   DECLARE VALORANTES DECIMAL(15,2);
   DECLARE QTDEANTES DECIMAL(15,4);    
   DECLARE EXCLUIBCPISCOFINS CHAR(1);
   
   SET VALORANTES = OLD.VALORUNITARIO;
