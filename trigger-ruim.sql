    if (creditotroco <> '1' and cast(replace(new.valorpagovarchar,',','.') as DECIMAL(15,2)) > 0) then                         
        
		   OPEN SQLPAGOCLIENTE;
	      
			LOOPFORMAPAGAMENTO : Loop
				Fetch SQLPAGOCLIENTE INTO pagocliente;							
				if DONE = TRUE then
					leave LOOPFORMAPAGAMENTO;
				END if;				
			END loop LOOPFORMAPAGAMENTO;
					   
	      CLOSE SQLPAGOCLIENTE;
                

