			END loop LOOPFORMAPAGAMENTO;
					   
	      CLOSE SQLPAGOUCLIENTE;
	      
        	OPEN SQLTOTALNOTA;
        	
			LOOPFORMAPAGAMENTO : Loop
				Fetch SQLTOTALNOTA INTO totalnota;							
				if DONE = TRUE then
					leave LOOPFORMAPAGAMENTO;
				END if;	   	
			END loop LOOPFORMAPAGAMENTO;
					   
	      CLOSE SQLTOTALNOTA;
	      
         if ((pagoucliente + pagocliente) > totalnota) then
             SET troco = (pagoucliente + pagocliente) - totalnota;
